-- z-kb 评估域 MySQL 元数据表（幂等，可重复执行）
-- 与 db/h2/evaluation-kb.sql 保持同构；索引随建表内联。
-- id 由应用生成（UUID 字符串），QA 集合按库单份、可版本化；跑批固定集合版本、
-- 配置版本与 Judge 版本，并用 zkb_kb_snapshot 钉住当时的物料、产物与检索块。

CREATE TABLE IF NOT EXISTS zkb_eval_dataset (
    id VARCHAR(64) NOT NULL COMMENT '主键',
    dataset_id VARCHAR(64) NOT NULL COMMENT 'QA 集合业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL COMMENT '租户编码',
    kb_id VARCHAR(64) NOT NULL COMMENT '所属知识库业务标识',
    name VARCHAR(128) NOT NULL COMMENT '集合名称',
    version_no INT NOT NULL COMMENT '集合版本号，按库递增',
    status VARCHAR(16) NOT NULL COMMENT '状态：DRAFT/FROZEN/ARCHIVED',
    case_count INT NOT NULL DEFAULT 0 COMMENT '题目数',
    description VARCHAR(1000) NULL COMMENT '集合说明',
    published_by VARCHAR(64) NULL COMMENT '冻结人',
    published_at DATETIME(3) NULL COMMENT '冻结时间',
    is_deleted INT NOT NULL DEFAULT 0 COMMENT '0-未删除 1-已删除',
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_eval_dataset_version (tenant_code, kb_id, version_no, is_deleted),
    UNIQUE KEY uk_zkb_eval_dataset_id (tenant_code, dataset_id, is_deleted),
    KEY idx_zkb_eval_dataset_status (tenant_code, kb_id, status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '评测 QA 集合，单库单份可版本化';

CREATE TABLE IF NOT EXISTS zkb_eval_case (
    id VARCHAR(64) NOT NULL,
    case_id VARCHAR(64) NOT NULL COMMENT '题目业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    dataset_pk VARCHAR(64) NOT NULL COMMENT 'QA 集合主键',
    dataset_id VARCHAR(64) NOT NULL COMMENT 'QA 集合业务标识',
    dataset_version_no INT NOT NULL COMMENT 'QA 集合版本号快照',
    case_no INT NOT NULL COMMENT '题号，从 1 递增',
    question VARCHAR(2000) NOT NULL COMMENT '问题',
    expected_answer TEXT NULL COMMENT '期望答案',
    expected_behavior VARCHAR(16) NOT NULL COMMENT '期望行为：ANSWER/REFUSE',
    expected_evidence TEXT NULL COMMENT '期望证据 JSON：materialId/keywords',
    entry_type VARCHAR(32) NOT NULL DEFAULT 'DOCUMENT' COMMENT '入口类型，本期固定文档',
    tags VARCHAR(255) NULL COMMENT '标签，逗号分隔',
    status VARCHAR(16) NOT NULL COMMENT '状态：ACTIVE/DISABLED',
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_eval_case_id (tenant_code, case_id, is_deleted),
    KEY idx_zkb_eval_case_dataset (tenant_code, dataset_pk),
    KEY idx_zkb_eval_case_no (tenant_code, dataset_pk, case_no)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '评测题目';

CREATE TABLE IF NOT EXISTS zkb_eval_run (
    id VARCHAR(64) NOT NULL,
    run_id VARCHAR(64) NOT NULL COMMENT '跑批业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    dataset_pk VARCHAR(64) NOT NULL COMMENT 'QA 集合主键',
    dataset_id VARCHAR(64) NOT NULL COMMENT 'QA 集合业务标识',
    dataset_version_no INT NOT NULL COMMENT 'QA 集合版本号',
    snapshot_id VARCHAR(64) NOT NULL COMMENT '内容快照业务标识',
    config_version VARCHAR(64) NOT NULL COMMENT '库配置版本',
    task_config_version VARCHAR(64) NOT NULL COMMENT '任务配置版本（测评跑批）',
    judge_mode VARCHAR(16) NOT NULL COMMENT '评分方式：LOCAL_RULE',
    judge_version VARCHAR(64) NOT NULL COMMENT 'Judge 版本',
    judge_config TEXT NULL COMMENT 'Judge 配置快照 JSON',
    retrieval_config TEXT NULL COMMENT '检索配置快照 JSON',
    index_generation VARCHAR(128) NOT NULL COMMENT '索引代际',
    input_fingerprint CHAR(64) NOT NULL COMMENT '输入指纹',
    scope_type VARCHAR(16) NOT NULL COMMENT '范围：FULL/STAGE',
    stage_code VARCHAR(16) NULL COMMENT '单阶段跑批阶段：S1–S8',
    baseline_run_id VARCHAR(64) NULL COMMENT '指定基线跑批业务标识',
    status VARCHAR(16) NOT NULL COMMENT '状态：QUEUED/RUNNING/SUCCEEDED/FAILED',
    result_usable INT NOT NULL DEFAULT 0 COMMENT '结果是否可用：1-可用 0-不可用',
    unusable_reason VARCHAR(64) NULL COMMENT '不可用原因编码',
    case_total INT NOT NULL DEFAULT 0 COMMENT '题目总数',
    case_done INT NOT NULL DEFAULT 0 COMMENT '已完成题目数',
    retrieval_truncated INT NOT NULL DEFAULT 0 COMMENT '检索扫描是否截断',
    started_at DATETIME(3) NULL COMMENT '开始时间',
    finished_at DATETIME(3) NULL COMMENT '完成时间',
    duration_ms BIGINT NULL COMMENT '耗时毫秒',
    error_code VARCHAR(32) NULL COMMENT '失败错误码',
    error_message VARCHAR(1000) NULL COMMENT '失败摘要',
    triggered_by VARCHAR(64) NULL COMMENT '发起人',
    reused_from_run_id VARCHAR(64) NULL COMMENT '复用来源跑批业务标识',
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_eval_run_id (tenant_code, run_id, is_deleted),
    KEY idx_zkb_eval_run_kb (tenant_code, kb_id, id),
    KEY idx_zkb_eval_run_fingerprint (tenant_code, kb_id, input_fingerprint, status, finished_at, id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '评测跑批';

CREATE TABLE IF NOT EXISTS zkb_eval_result (
    id VARCHAR(64) NOT NULL,
    tenant_code VARCHAR(64) NOT NULL,
    run_id VARCHAR(64) NOT NULL COMMENT '跑批业务标识',
    metric_code VARCHAR(64) NOT NULL COMMENT '指标编码',
    metric_name VARCHAR(128) NOT NULL COMMENT '指标名称',
    metric_layer VARCHAR(16) NOT NULL COMMENT '指标层：CORE/PRECONDITION/DIAGNOSTIC/RUNTIME',
    stage_code VARCHAR(16) NOT NULL COMMENT '阶段或分组编码',
    metric_value DECIMAL(18,6) NULL COMMENT '指标值',
    unit VARCHAR(16) NOT NULL DEFAULT 'ratio' COMMENT '单位',
    target_value DECIMAL(18,6) NULL COMMENT '目标值',
    status VARCHAR(16) NOT NULL COMMENT '状态：PASS/FAIL/PARTIAL/NOT_APPLICABLE/NOT_CONNECTED',
    sample_size INT NOT NULL DEFAULT 0 COMMENT '样本数',
    attribution VARCHAR(64) NULL COMMENT '归因段',
    note VARCHAR(1000) NULL COMMENT '口径与限制说明',
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_eval_result_metric (tenant_code, run_id, metric_code, is_deleted),
    KEY idx_zkb_eval_result_run (tenant_code, run_id, metric_layer)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '评测指标结果';

CREATE TABLE IF NOT EXISTS zkb_eval_case_result (
    id VARCHAR(64) NOT NULL,
    tenant_code VARCHAR(64) NOT NULL,
    run_id VARCHAR(64) NOT NULL COMMENT '跑批业务标识',
    case_id VARCHAR(64) NOT NULL COMMENT '题目业务标识',
    question VARCHAR(2000) NOT NULL COMMENT '问题快照',
    answer TEXT NULL COMMENT '本次答案',
    answer_mode VARCHAR(24) NOT NULL COMMENT '答案模式：EXTRACTIVE_TOP3/REFUSED',
    retrieved TEXT NULL COMMENT '前 10 条召回 JSON',
    citations TEXT NULL COMMENT '引用块 JSON',
    metrics TEXT NULL COMMENT '逐题指标 JSON',
    stage_trace TEXT NULL COMMENT '逐阶段判定 JSON',
    latency_ms BIGINT NULL COMMENT '评测检索耗时毫秒',
    error_message VARCHAR(1000) NULL COMMENT '单题失败摘要',
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_eval_case_result (tenant_code, run_id, case_id, is_deleted),
    KEY idx_zkb_eval_case_result_run (tenant_code, run_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '逐题评测结果';

