CREATE TABLE IF NOT EXISTS zkb_kb_snapshot (
    id VARCHAR(64) NOT NULL,
    snapshot_id VARCHAR(64) NOT NULL COMMENT '内容快照业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL COMMENT '所属知识库业务标识',
    config_version VARCHAR(64) NOT NULL COMMENT '库配置版本',
    ontology_version VARCHAR(64) NOT NULL COMMENT '本体定义版本或图谱空间标识',
    index_generation VARCHAR(128) NOT NULL COMMENT '索引代际',
    fingerprint CHAR(64) NOT NULL COMMENT '成员清单指纹',
    status VARCHAR(16) NOT NULL COMMENT '状态：BUILDING/READY/FAILED',
    artifact_manifest TEXT NULL COMMENT '成员与产物清单摘要 JSON',
    material_count INT NOT NULL DEFAULT 0 COMMENT '物料数',
    artifact_count INT NOT NULL DEFAULT 0 COMMENT '产物数',
    chunk_count INT NOT NULL DEFAULT 0 COMMENT '已索引检索块数',
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_snapshot_id (tenant_code, snapshot_id, is_deleted),
    KEY idx_zkb_snapshot_kb (tenant_code, kb_id, id),
    KEY idx_zkb_snapshot_fingerprint (tenant_code, kb_id, fingerprint, index_generation, status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '知识库内容快照，只在跑批等时刻生成';

CREATE TABLE IF NOT EXISTS zkb_kb_snapshot_item (
    id VARCHAR(64) NOT NULL,
    tenant_code VARCHAR(64) NOT NULL,
    snapshot_id VARCHAR(64) NOT NULL COMMENT '内容快照业务标识',
    item_type VARCHAR(16) NOT NULL COMMENT '成员类型：MATERIAL/ARTIFACT',
    item_key VARCHAR(255) NOT NULL COMMENT '成员唯一键，如 MATERIAL:{id}',
    material_id VARCHAR(64) NULL COMMENT '物料业务标识',
    material_version_id VARCHAR(64) NULL COMMENT '物料版本业务标识',
    artifact_type VARCHAR(32) NULL COMMENT '产物类型',
    artifact_version_id VARCHAR(64) NULL COMMENT '产物版本业务标识',
    index_generation VARCHAR(128) NULL COMMENT '索引代际',
    checksum CHAR(64) NULL COMMENT '成员内容指纹',
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
