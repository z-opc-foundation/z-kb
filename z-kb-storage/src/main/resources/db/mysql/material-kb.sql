-- z-kb 物料域 MySQL 元数据表（幂等，可重复执行）
-- 原始文件字节走对象存储（KbOriginalFileStore），这里只放元数据；文档正文独立存解析稿表。

CREATE TABLE IF NOT EXISTS zkb_material (
    id VARCHAR(64) NOT NULL COMMENT '主键',
    material_id VARCHAR(64) NOT NULL COMMENT '物料业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL COMMENT '租户编码',
    kb_id VARCHAR(64) NOT NULL COMMENT '所属知识库业务标识',
    material_type VARCHAR(16) NOT NULL COMMENT 'DOCUMENT/CODE/DATA_TABLE',
    entry_type VARCHAR(16) NOT NULL COMMENT 'DOCUMENT/TABLE/IMAGE/AUDIO/VIDEO/WEB/CODE/JSON',
    title VARCHAR(255) NOT NULL COMMENT '标题，默认取文件名',
    source_type VARCHAR(32) NULL COMMENT '来源类型：LOCAL/YUQUE/GIT/DATABASE',
    source_binding_id VARCHAR(64) NULL COMMENT '来源绑定标识，本地上传为空',
    category_id VARCHAR(64) NULL COMMENT '分类标识，空表示未分类',
    material_status VARCHAR(16) NOT NULL COMMENT 'REGISTERED/ACTIVE/UPDATING/DELETED',
    fingerprint CHAR(64) NOT NULL COMMENT '内容 SHA-256 指纹',
    current_version_id VARCHAR(64) NULL COMMENT '当前有效版本业务标识',
    metadata TEXT NULL COMMENT '扩展元数据 JSON',
    registered_by VARCHAR(64) NULL COMMENT '登记人',
    registered_at DATETIME(3) NOT NULL COMMENT '登记时间',
    is_deleted TINYINT NOT NULL DEFAULT 0 COMMENT '0-未删除 1-已删除',
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_material_id (tenant_code, material_id, is_deleted),
    UNIQUE KEY uk_zkb_material_fp (tenant_code, kb_id, material_type, fingerprint, is_deleted),
    KEY idx_zkb_material_kb (tenant_code, kb_id, is_deleted, create_time),
    KEY idx_zkb_material_category (tenant_code, kb_id, category_id),
    KEY idx_zkb_material_source (tenant_code, kb_id, source_binding_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '物料主表';

CREATE TABLE IF NOT EXISTS zkb_material_version (
    id VARCHAR(64) NOT NULL,
    version_id VARCHAR(64) NOT NULL COMMENT '版本业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    material_id VARCHAR(64) NOT NULL,
    version_no INT NOT NULL COMMENT '版本序号，从 1 递增',
    fingerprint CHAR(64) NOT NULL,
    source_version VARCHAR(64) NULL COMMENT '来源侧版本号',
    current_parsed_draft_id VARCHAR(64) NULL COMMENT '当前解析稿业务标识',
    version_status VARCHAR(16) NOT NULL COMMENT 'REGISTERED/PARSING/PARSED/FAILED/SUPERSEDED',
    file_name VARCHAR(255) NOT NULL,
    file_ext VARCHAR(16) NULL,
    size_bytes BIGINT NOT NULL,
    original_url VARCHAR(1024) NULL COMMENT '原件在对象存储中的地址',
    registered_at DATETIME(3) NOT NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_material_version_id (tenant_code, version_id, is_deleted),
    UNIQUE KEY uk_zkb_material_version_no (tenant_code, material_id, version_no, is_deleted),
    KEY idx_zkb_material_version (tenant_code, material_id, version_no),
    KEY idx_zkb_material_version_status (tenant_code, kb_id, version_status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '物料版本，不可变';

CREATE TABLE IF NOT EXISTS zkb_material_parsed_draft (
    id VARCHAR(64) NOT NULL,
    draft_id VARCHAR(64) NOT NULL COMMENT '解析稿业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    material_id VARCHAR(64) NOT NULL,
    material_version_id VARCHAR(64) NOT NULL,
    parser_name VARCHAR(64) NOT NULL,
    parser_version VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL COMMENT 'PARSING/READY/FAILED/SUPERSEDED',
    text_content MEDIUMTEXT NULL COMMENT '解析文本',
    failure_reason VARCHAR(1000) NULL,
    parsed_at DATETIME(3) NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_draft_id (tenant_code, draft_id, is_deleted),
    KEY idx_zkb_draft_version (tenant_code, material_version_id, parsed_at),
    KEY idx_zkb_draft_material (tenant_code, material_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '解析稿，不可变';

CREATE TABLE IF NOT EXISTS zkb_category (
    id VARCHAR(64) NOT NULL,
    category_id VARCHAR(64) NOT NULL COMMENT '分类业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    parent_id VARCHAR(64) NULL COMMENT '父分类标识，空为根分类',
    name VARCHAR(50) NOT NULL COMMENT '分类名称，同层不可重复',
    sort_no INT NOT NULL DEFAULT 0,
    node_kind VARCHAR(16) NOT NULL DEFAULT 'FOLDER' COMMENT 'FOLDER/SOURCE/SOURCE_BOOK/SOURCE_REPO',
    ext_json TEXT NULL COMMENT '节点绑定信息 JSON',
    is_deleted TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_category_id (tenant_code, category_id, is_deleted),
    KEY idx_zkb_category_parent (tenant_code, kb_id, parent_id, sort_no)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '库内资料分类';
