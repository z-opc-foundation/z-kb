-- z-kb 萃取/概念/图谱 MySQL 元数据表（幂等，可重复执行）
-- 萃取条目直接落表，不重复登记产物；图谱以 "kb:" + kbId 作为库级物理空间键。

CREATE TABLE IF NOT EXISTS zkb_extraction_item (
    id VARCHAR(64) NOT NULL COMMENT '主键',
    item_id VARCHAR(64) NOT NULL COMMENT '条目业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL COMMENT '租户编码',
    kb_id VARCHAR(64) NOT NULL COMMENT '所属知识库业务标识',
    material_id VARCHAR(64) NOT NULL COMMENT '来源物料业务标识',
    material_version_id VARCHAR(64) NOT NULL COMMENT '来源物料版本业务标识',
    item_type VARCHAR(16) NOT NULL COMMENT '条目类型：SUMMARY/QUESTION/TERM/FAQ',
    seq INT NOT NULL DEFAULT 0 COMMENT '同类条目序号，从 1 递增',
    title VARCHAR(255) NOT NULL COMMENT '条目标题',
    content TEXT NOT NULL COMMENT '条目正文',
    evidence_json TEXT NULL COMMENT '证据引用 JSON，记录检索块序号与字符范围',
    is_deleted TINYINT NOT NULL DEFAULT 0 COMMENT '0-未删除 1-已删除',
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_extract_item_id (tenant_code, item_id, is_deleted),
    KEY idx_zkb_extract_version (tenant_code, material_version_id, item_type, seq, id),
    KEY idx_zkb_extract_material (tenant_code, kb_id, material_id, item_type)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '本地规则萃取条目';

CREATE TABLE IF NOT EXISTS zkb_concept (
    id VARCHAR(64) NOT NULL COMMENT '主键',
    concept_id VARCHAR(64) NOT NULL COMMENT '概念业务标识，按租户+库+规范化名称确定性生成',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL COMMENT '概念名称，取首次涌现时的写法',
    normalized_name VARCHAR(255) NOT NULL COMMENT '规范化名称，归一与去重依据',
    concept_type VARCHAR(16) NOT NULL DEFAULT 'TERM' COMMENT 'TERM/TOPIC',
    status VARCHAR(16) NOT NULL DEFAULT 'EMERGING' COMMENT 'EMERGING/CONFIRMED',
    definition VARCHAR(500) NULL COMMENT '概念定义，取首次命中的术语句',
    aliases_json TEXT NULL COMMENT '别名 JSON，预留同义归并',
    mention_count INT NOT NULL DEFAULT 0 COMMENT '提及次数，按提及行 occurrence_count 求和',
    material_count INT NOT NULL DEFAULT 0 COMMENT '来源资料数，按 material_id 去重',
    first_material_id VARCHAR(64) NULL COMMENT '首次涌现来源物料业务标识',
    last_material_id VARCHAR(64) NULL COMMENT '最近一次涌现来源物料业务标识',
    evidence_json TEXT NULL COMMENT '首次涌现的证据引用 JSON',
    is_deleted TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_concept_id (tenant_code, concept_id, is_deleted),
    UNIQUE KEY uk_zkb_concept_name (tenant_code, kb_id, normalized_name, is_deleted),
    KEY idx_zkb_concept_status (tenant_code, kb_id, status),
    KEY idx_zkb_concept_material (tenant_code, kb_id, last_material_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '知识库级概念模型';

CREATE TABLE IF NOT EXISTS zkb_concept_mention (
    id VARCHAR(64) NOT NULL,
    mention_id VARCHAR(64) NOT NULL COMMENT '提及业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    concept_id VARCHAR(64) NOT NULL,
    material_id VARCHAR(64) NOT NULL,
    material_version_id VARCHAR(64) NOT NULL,
    material_title VARCHAR(255) NULL COMMENT '来源物料标题冗余，便于概念详情直接展示',
    extraction_item_id VARCHAR(64) NULL COMMENT '桥接的萃取条目业务标识',
    chunk_ordinal INT NOT NULL DEFAULT 0 COMMENT '首次出现的检索块序号',
    occurrence_count INT NOT NULL DEFAULT 1 COMMENT '该资料内出现次数',
    evidence_json TEXT NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_mention_id (tenant_code, mention_id, is_deleted),
    UNIQUE KEY uk_zkb_mention_concept_version (tenant_code, material_version_id, concept_id, is_deleted),
    KEY idx_zkb_mention_concept (tenant_code, kb_id, concept_id),
    KEY idx_zkb_mention_material (tenant_code, material_id),
    KEY idx_zkb_mention_version (tenant_code, material_version_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '概念提及：萃取输出与概念模型的桥接';

CREATE TABLE IF NOT EXISTS zkb_graph_node (
    id VARCHAR(64) NOT NULL,
    node_id VARCHAR(128) NOT NULL COMMENT '图节点业务标识',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    graph_space_key VARCHAR(128) NOT NULL COMMENT '图谱空间键，本期为 kb:<kbId>',
    node_type VARCHAR(16) NOT NULL COMMENT 'MATERIAL/CONCEPT',
    concept_id VARCHAR(64) NULL COMMENT '所属概念模型标识，CONCEPT 节点必填',
    name VARCHAR(255) NOT NULL,
    material_id VARCHAR(64) NOT NULL COMMENT '证据来源物料业务标识',
    evidence_json TEXT NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    KEY idx_zkb_graph_node_space (tenant_code, kb_id, graph_space_key),
    KEY idx_zkb_graph_node_material (tenant_code, material_id),
    KEY idx_zkb_graph_node_node (tenant_code, node_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '本地规则图谱节点';

CREATE TABLE IF NOT EXISTS zkb_graph_edge (
    id VARCHAR(64) NOT NULL,
    edge_id VARCHAR(128) NOT NULL COMMENT '图边业务标识',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    graph_space_key VARCHAR(128) NOT NULL COMMENT '图谱空间键，本期为 kb:<kbId>',
    edge_type VARCHAR(16) NOT NULL COMMENT 'MENTIONS/RELATED_TO',
    source_node_id VARCHAR(128) NOT NULL,
    target_node_id VARCHAR(128) NOT NULL,
    material_id VARCHAR(64) NOT NULL,
    evidence_json TEXT NULL,
    is_deleted TINYINT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    KEY idx_zkb_graph_edge_space (tenant_code, kb_id, graph_space_key),
    KEY idx_zkb_graph_edge_material (tenant_code, material_id),
    KEY idx_zkb_graph_edge_edge (tenant_code, edge_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '本地规则图谱边';
