-- z-kb 编译域 MySQL 元数据表（幂等，可重复执行）
-- 与 db/h2/compilation-kb.sql 保持同构；索引随建表内联。
-- 编译作业既是单文件任务（scope_type=SINGLE）也是多文件组别（WORKSPACE/CATEGORY/FOLDER），
-- 组别不单独落表；阶段按物料版本分行，产物登记簿只记「产出了什么」，内容在检索块表。

CREATE TABLE IF NOT EXISTS zkb_compilation_job (
    id VARCHAR(64) NOT NULL COMMENT '主键',
    job_id VARCHAR(64) NOT NULL COMMENT '编译作业业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL COMMENT '租户编码',
    kb_id VARCHAR(64) NOT NULL COMMENT '所属知识库业务标识',
    name VARCHAR(255) NOT NULL COMMENT '作业名称',
    task_type VARCHAR(32) NOT NULL DEFAULT 'COMPILATION' COMMENT '任务性质',
    scope_type VARCHAR(16) NOT NULL COMMENT 'SINGLE/WORKSPACE/CATEGORY/FOLDER',
    scope_id VARCHAR(64) NULL COMMENT '范围对象标识，分类或文件夹节点',
    scope_count INT NOT NULL DEFAULT 1 COMMENT '冻结输入条目数',
    material_id VARCHAR(64) NULL COMMENT '首条输入物料业务标识，便于按物料复用',
    material_version_id VARCHAR(64) NULL COMMENT '首条输入物料版本业务标识',
    total_count INT NOT NULL DEFAULT 0 COMMENT '成员总数',
    success_count INT NOT NULL DEFAULT 0 COMMENT '成功成员数',
    failed_count INT NOT NULL DEFAULT 0 COMMENT '失败成员数',
    input_snapshot VARCHAR(4000) NOT NULL COMMENT '冻结输入快照 JSON：[{materialId,versionId,title}]',
    pipeline_type VARCHAR(32) NOT NULL DEFAULT 'DOCUMENT' COMMENT '流水线类型',
    config_version VARCHAR(64) NULL COMMENT '编译配置版本',
    config_snapshot VARCHAR(4000) NULL COMMENT '编译配置快照 JSON',
    compiler_version VARCHAR(64) NOT NULL COMMENT '编译器版本',
    run_status VARCHAR(16) NOT NULL COMMENT 'QUEUED/RUNNING/PAUSED/COMPLETED/FAILED/CANCELED',
    milestone VARCHAR(8) NOT NULL DEFAULT 'NONE' COMMENT 'NONE/M1/M2',
    current_stage VARCHAR(16) NULL COMMENT '当前阶段',
    chunk_count INT NOT NULL DEFAULT 0 COMMENT '检索块总数',
    round_no INT NOT NULL DEFAULT 1 COMMENT '重跑轮次，从 1 递增',
    m1_at DATETIME(3) NULL COMMENT 'M1 达成时间',
    m2_at DATETIME(3) NULL COMMENT 'M2 达成时间',
    started_at DATETIME(3) NULL COMMENT '开始时间',
    finished_at DATETIME(3) NULL COMMENT '结束时间',
    failure_summary VARCHAR(1000) NULL COMMENT '失败摘要',
    is_deleted INT NOT NULL DEFAULT 0 COMMENT '0-未删除 1-已删除',
    create_by VARCHAR(64) NULL COMMENT '创建人',
    update_by VARCHAR(64) NULL COMMENT '更新人',
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_job_id (tenant_code, job_id, is_deleted),
    KEY idx_zkb_job_kb (tenant_code, kb_id, is_deleted, create_time),
    KEY idx_zkb_job_material (tenant_code, material_id, material_version_id),
    KEY idx_zkb_job_scope (tenant_code, kb_id, scope_type, run_status)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '编译作业与编译组别';

CREATE TABLE IF NOT EXISTS zkb_compilation_stage (
    id VARCHAR(64) NOT NULL,
    tenant_code VARCHAR(64) NOT NULL,
    job_id VARCHAR(64) NOT NULL COMMENT '所属编译作业业务标识',
    material_id VARCHAR(64) NOT NULL COMMENT '物料业务标识',
    material_version_id VARCHAR(64) NOT NULL COMMENT '物料版本业务标识',
    stage VARCHAR(16) NOT NULL COMMENT 'REGISTER/PARSE/CHUNK/INDEX/EXTRACT',
    status VARCHAR(16) NOT NULL COMMENT 'PENDING/READY/QUEUED/RUNNING/SUCCEEDED/FAILED/CANCELED/SKIPPED',
    round_no INT NOT NULL DEFAULT 1 COMMENT '所属重跑轮次',
    seq_no INT NOT NULL DEFAULT 0 COMMENT '阶段顺序',
    input_ref VARCHAR(255) NULL COMMENT '输入引用',
    output_ref VARCHAR(255) NULL COMMENT '输出引用（产物标识等）',
    item_count INT NOT NULL DEFAULT 0 COMMENT '阶段产出条数',
    detail VARCHAR(1000) NULL COMMENT '结果说明',
    failure_summary VARCHAR(1000) NULL COMMENT '失败摘要',
    started_at DATETIME(3) NULL,
    finished_at DATETIME(3) NULL,
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_stage (tenant_code, job_id, material_version_id, stage, round_no, is_deleted),
    KEY idx_zkb_stage_job (tenant_code, job_id, round_no, material_version_id, seq_no),
    KEY idx_zkb_stage_version (tenant_code, material_version_id, create_time)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '编译阶段执行明细，按物料版本分行';

CREATE TABLE IF NOT EXISTS zkb_artifact (
    id VARCHAR(64) NOT NULL,
    artifact_id VARCHAR(64) NOT NULL COMMENT '产物业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    material_id VARCHAR(64) NULL COMMENT '主来源物料业务标识',
    material_version_id VARCHAR(64) NULL COMMENT '主来源物料版本业务标识',
    artifact_type VARCHAR(32) NOT NULL COMMENT 'RETRIEVAL_CHUNK/SUMMARY/QUESTION_SET/TERM/FAQ/GRAPH_BLOCK/WIKI_PAGE/WIKI_DOC',
    title VARCHAR(255) NOT NULL,
    lifecycle_status VARCHAR(16) NOT NULL COMMENT 'DRAFT/PUBLISHED/OFFLINE/ARCHIVED/INVALIDATED',
    retrieval_state VARCHAR(16) NOT NULL COMMENT 'NOT_INDEXED/INDEXED/STALE/REMOVED',
    current_version_id VARCHAR(64) NULL COMMENT '当前产物版本业务标识',
    evidence_ref VARCHAR(255) NOT NULL COMMENT '证据引用，至少一条',
    created_by VARCHAR(64) NULL COMMENT '编译者标识',
    published_at DATETIME(3) NULL,
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_artifact_id (tenant_code, artifact_id, is_deleted),
    KEY idx_zkb_artifact_kb (tenant_code, kb_id, artifact_type),
    KEY idx_zkb_artifact_material (tenant_code, material_id),
    KEY idx_zkb_artifact_version (tenant_code, material_version_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '产物登记簿，一件产物一行';

CREATE TABLE IF NOT EXISTS zkb_artifact_version (
    id VARCHAR(64) NOT NULL,
    artifact_version_id VARCHAR(64) NOT NULL COMMENT '产物版本业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    artifact_id VARCHAR(64) NOT NULL,
    version_no INT NOT NULL COMMENT '产物版本序号，从 1 递增',
    content_hash CHAR(64) NOT NULL COMMENT '内容 SHA-256 指纹',
    storage_ref VARCHAR(255) NOT NULL COMMENT '内容存储引用，如检索块集合标识',
    compiler_version VARCHAR(64) NOT NULL,
    config_version VARCHAR(64) NOT NULL,
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_artifact_version_id (tenant_code, artifact_version_id, is_deleted),
    KEY idx_zkb_artifact_version (tenant_code, artifact_id, version_no)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '产物版本，不可变';

CREATE TABLE IF NOT EXISTS zkb_retrieval_chunk (
    id VARCHAR(64) NOT NULL,
    chunk_id VARCHAR(64) NOT NULL COMMENT '检索块业务标识（UUID）',
    tenant_code VARCHAR(64) NOT NULL,
    kb_id VARCHAR(64) NOT NULL,
    source_type VARCHAR(16) NOT NULL DEFAULT 'MATERIAL' COMMENT 'MATERIAL/WIKI_PAGE/GRAPH_NODE',
    source_id VARCHAR(64) NOT NULL DEFAULT '' COMMENT '来源对象业务标识',
    source_version_id VARCHAR(64) NULL COMMENT '来源对象版本标识',
    parent_chunk_id VARCHAR(64) NULL COMMENT '父块标识，章节块下的段落块指向父块',
    chunk_role VARCHAR(16) NOT NULL DEFAULT 'PASSAGE' COMMENT 'SECTION 章节块、PASSAGE 段落块',
    material_id VARCHAR(64) NULL COMMENT '来源物料业务标识',
    material_version_id VARCHAR(64) NULL COMMENT '来源物料版本业务标识',
    artifact_id VARCHAR(64) NOT NULL COMMENT '对应产物业务标识',
    artifact_version_id VARCHAR(64) NOT NULL COMMENT '对应产物版本业务标识',
    ordinal INT NOT NULL COMMENT '块序号，从 1 递增',
    heading VARCHAR(255) NULL COMMENT '所属章节标题',
    content TEXT NOT NULL COMMENT '块正文',
    char_count INT NOT NULL COMMENT '字符数',
    index_state VARCHAR(16) NOT NULL COMMENT 'NOT_INDEXED/INDEXED/FAILED',
    embedding_model VARCHAR(64) NULL COMMENT '向量模型标识',
    embedding MEDIUMTEXT NULL COMMENT '向量值（CSV 浮点）',
    indexed_at DATETIME(3) NULL COMMENT '索引完成时间',
    is_deleted INT NOT NULL DEFAULT 0,
    create_by VARCHAR(64) NULL,
    update_by VARCHAR(64) NULL,
    create_time DATETIME(3) NULL,
    update_time DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_zkb_chunk_id (tenant_code, chunk_id, is_deleted),
    KEY idx_zkb_chunk_kb (tenant_code, kb_id, source_type, source_id),
    KEY idx_zkb_chunk_material (tenant_code, kb_id, material_id),
    KEY idx_zkb_chunk_version (tenant_code, material_version_id, ordinal),
    KEY idx_zkb_chunk_parent (tenant_code, parent_chunk_id),
    KEY idx_zkb_chunk_role_state (tenant_code, kb_id, chunk_role, index_state, indexed_at, material_id, ordinal),
    KEY idx_zkb_chunk_artifact (tenant_code, artifact_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '统一检索池：物料块、Wiki 页块与图谱实体块';
